from __future__ import annotations

import argparse
import re
from collections import Counter, defaultdict
from pathlib import Path

from src.pipeline import ROOT, chunks_for_strategy

_MARKS = re.compile(r"(?i):(?:un)?selected:|[☒☐]")
_HEADER = re.compile(r"(?i)^\s*(?:page\s+)?\d+(?:\s+of\s+\d+)?\s*$")
_SENTENCE = re.compile(r"[^.!?]+[.!?]?")
_MAX_BLOCK_TOKENS = 450
REFERENCE_PRICE_PER_MILLION_INPUT_TOKENS_USD = 0.02
OPENAI_PRICE_SOURCE_URL = "https://developers.openai.com/api/docs/pricing/"


def _metrics(chunks: list[dict]) -> dict[str, float | int]:
    token_encoder = __import__("tiktoken").get_encoding("cl100k_base")
    table_chunks: Counter[str] = Counter()
    expected_table_intros: set[str] = set()
    present_table_intros: set[str] = set()
    sentences_by_source: dict[str, set[str]] = defaultdict(set)
    boundary_pages: dict[tuple[str, str], set[int]] = defaultdict(set)
    duplicate_sentences = 0
    mid_sentence = 0
    oversized_chunks = 0
    oversized_table_chunks = 0
    lengths = []
    token_total = 0
    max_chunk_tokens = 0
    marks = 0

    for chunk in chunks:
        text = chunk["text"]
        lengths.append(len(text))
        token_count = len(token_encoder.encode(text))
        token_total += token_count
        max_chunk_tokens = max(max_chunk_tokens, token_count)
        marks += len(_MARKS.findall(text))
        if chunk["strategy"] == "blocks" and token_count > _MAX_BLOCK_TOKENS:
            oversized_chunks += 1
            if chunk.get("table_raw"):
                oversized_table_chunks += 1
        body = text.split("\n\n", 1)[-1].strip()
        if body and (body[0].islower() or body[0] in ",.;:"):
            mid_sentence += 1
        for table_id in chunk.get("_table_ids", []):
            table_chunks[table_id] += 1
        for intro in chunk.get("_table_intros", []):
            expected_table_intros.add(intro["block_id"])
            if intro["text"] in text:
                present_table_intros.add(intro["block_id"])
        for match in _SENTENCE.finditer(body):
            sentence = " ".join(match.group(0).casefold().split())
            if len(sentence) < 25:
                continue
            if sentence in sentences_by_source[chunk["source"]]:
                duplicate_sentences += 1
            else:
                sentences_by_source[chunk["source"]].add(sentence)
        if chunk.get("page") is not None:
            nonempty_lines = [line.strip() for line in body.splitlines() if line.strip()]
            for line in nonempty_lines[:2] + nonempty_lines[-2:]:
                if len(line) <= 120 and not line.startswith("|"):
                    boundary_pages[(chunk["source"], line.casefold())].add(chunk["page"])
        if any(_HEADER.match(line) for line in body.splitlines()):
            boundary_pages[(chunk["source"], "explicit-page-marker")].add(chunk["page"] or 0)

    repeated_headers = sum(
        len(pages) >= 2 for pages in boundary_pages.values()
    )

    return {
        "documents": len({chunk["source"] for chunk in chunks}),
        "chunks": len(chunks),
        "tokens": token_total,
        "estimated_usd": round(
            token_total * REFERENCE_PRICE_PER_MILLION_INPUT_TOKENS_USD / 1_000_000, 6
        ),
        "avg_chars": round(sum(lengths) / max(len(lengths), 1), 1),
        "max_chunk_tokens": max_chunk_tokens,
        "tables_detected": len(table_chunks),
        "tables_in_multiple_chunks": sum(count > 1 for count in table_chunks.values()),
        "tables_missing_introduction": len(expected_table_intros - present_table_intros),
        "duplicate_sentences": duplicate_sentences,
        "mid_sentence_starts": mid_sentence,
        "selection_marks": marks,
        "header_footer_lines": repeated_headers,
        "oversized_block_chunks": oversized_chunks,
        "oversized_table_chunks": oversized_table_chunks,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Measure chunk size and structural quality for A and B.")
    parser.add_argument("--strategies", nargs="+", choices=["recursive", "blocks"], default=["recursive", "blocks"])
    args = parser.parse_args()
    results = {strategy: _metrics(chunks_for_strategy(strategy)) for strategy in args.strategies}
    columns = list(next(iter(results.values())))
    report = [
        "# Chunk quality",
        "",
        "Metrics are computed from the included manifest sources. Counts are generated by this run.",
        "",
        "A (`recursive`) uses 800 characters with 100 characters of overlap. B (`blocks`) targets 450 "
        "tokens without overlap, carries the document/section prefix, keeps each table atomic, and splits "
        "oversized code blocks on line boundaries. An 8-token reserve accounts for tokenization changes "
        "when the prefix and body are joined.",
        "",
        f"The USD estimate is an OpenAI reference only: "
        f"${REFERENCE_PRICE_PER_MILLION_INPUT_TOKENS_USD:.2f} per 1M input tokens for "
        f"`text-embedding-3-small` per the [official OpenAI pricing page]({OPENAI_PRICE_SOURCE_URL}). "
        "This is a reference estimate only, not the selected Gemini model's price or a charge. "
        "It excludes Qdrant charges/retries; this quality run itself makes no embedding or Qdrant write calls.",
        "",
        "| Strategy | " + " | ".join(columns) + " |",
        "|" + "---|" * (len(columns) + 1),
    ]
    for strategy, values in results.items():
        report.append("| " + strategy + " | " + " | ".join(str(values[column]) for column in columns) + " |")
    total_tokens = sum(int(values["tokens"]) for values in results.values())
    total_cost = total_tokens * REFERENCE_PRICE_PER_MILLION_INPUT_TOKENS_USD / 1_000_000
    report.extend([
        "",
        f"Embedding both strategies would process {total_tokens:,} tokens, estimated at "
        f"${total_cost:.6f} USD in total; this is a planning estimate and was not incurred.",
        "",
        "`tables_in_multiple_chunks` and `tables_missing_introduction` must remain 0 for B. The introduction "
        "check applies when the source paragraph immediately before a table ends with a colon. Tables exceeding "
        "450 tokens are intentionally kept whole and reported in `oversized_table_chunks`. "
        "`duplicate_sentences` counts repeated long sentences within a source; it can reflect authored "
        "repetition as well as overlap. `header_footer_lines` is a page-boundary heuristic; review the "
        "reported PDF counts against representative page boundaries before changing the cleaning rules. "
        "Only extractable text is measured; figure/image contents are not embedded.",
    ])
    output = ROOT / "docs" / "chunk_quality.md"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(report) + "\n", encoding="utf-8")
    print("\n".join(report))


if __name__ == "__main__":
    main()
